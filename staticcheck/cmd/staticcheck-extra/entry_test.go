package main_test

import (
	"errors"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

// TestCommandEntry checks thin command declarations through the analyzer CLI.
func TestCommandEntry(t *testing.T) {
	t.Parallel()

	binary := filepath.Join(t.TempDir(), "staticcheck-extra")
	build := exec.CommandContext(t.Context(), "go", "build", "-trimpath", "-o", binary, ".")
	if output, err := build.CombinedOutput(); err != nil {
		t.Fatalf("build analyzer: %v\n%s", err, output)
	}

	fixture := t.TempDir()
	writeFixtureFile(t, fixture, "go.mod", "module corp\n\ngo 1.27\n")
	writeFixtureFile(
		t,
		fixture,
		"cli/run.go",
		`package cli
func Run() error { return nil }
func Count() int { return 0 }
func Delete() {}
func Generic[T ~int](value T) T { return value }
`,
	)
	cases := map[string]struct {
		source string
		reject bool
	}{
		"wrapper": {
			source: `import("corp/cli";"fmt";"errors";"log/slog")
func run() error {
 if err := cli.Run(); err != nil && !errors.Is(err, nil) {
  wrapped := fmt.Errorf("run: %w", err)
  slog.Error("command failed", slog.Any("err", wrapped))
  return wrapped
 }
 return nil
}
func main() { _ = run() }`,
		},
		"status": {
			source: `import("corp/cli";"os";"log/slog")
const failed = 1
func main() {
 slog.Debug("command invoked")
 status := cli.Count()
 if status != 0 { slog.Error("command failed"); os.Exit(failed) }
}`,
		},
		"generic": {
			source: `import("corp/cli";"os")
func main() { os.Exit(cli.Generic(0)) }`,
		},
		"mapping": {
			source: `import("corp/cli";"os")
func main() { status := cli.Count(); switch status { case 0: os.Exit(0); default: os.Exit(1) } }`,
		},
		"assigned": {
			source: `import("corp/cli";"fmt")
func run() error {
 err := cli.Run()
 if err = cli.Run(); err != nil { return fmt.Errorf("run: %w", err) }
 return nil
}
func main() { _ = run() }`,
		},
		"loop":     {source: `func main() { for {} }`, reject: true},
		"grouped":  {source: `func work(first, second int) { for {} }`, reject: true},
		"expanded": {source: `func work(first int, second int) { for {} }`, reject: true},
		"changed":  {source: `func work(first int, second string) { for {} }`, reject: true},
		"parse": {
			source: `import "flag"
func main() { flag.Parse() }`,
			reject: true,
		},
		"standard": {
			source: `import "fmt"
func main() { fmt.Println("command implementation") }`,
			reject: true,
		},
		"setup": {
			source: `import("corp/cli";"os")
func main() { option := "value"; os.Exit(cli.Generic(len(option))) }`,
			reject: true,
		},
		"business": {
			source: `import "corp/cli"
func main() { count := cli.Count(); if count > 10 { cli.Delete() } }`,
			reject: true,
		},
		"helper": {
			source: `func main() { work() }
func work() { for {} }`,
			reject: true,
		},
		"generated": {source: `func main() { for {} }`, reject: true},
		"receiver": {
			source: `import("log/slog";"os")
func main() { slog.New(slog.NewTextHandler(os.Stderr, nil)).Info("started") }`,
			reject: true,
		},
		"constant": {
			source: `const status, option = 1, "setup"
func main() {}`,
			reject: true,
		},
		"duplicate": {
			source: `func main() {}
func init() { for {} }
func init() { for {} }`,
			reject: true,
		},
	}

	for name, test := range cases {
		header := "package main\n"
		filename := "main.go"
		if name == "generated" {
			header = "// Code generated by fixture. DO NOT EDIT.\n" + header
			filename = "main_gen.go"
		}

		writeFixtureFile(t, fixture, "cmd/"+name+"/"+filename, header+test.source+"\n")
	}

	writeFixtureFile(t, fixture, "cmd/main.go", "package main\nfunc main() { for {} }\n")

	check := exec.CommandContext(t.Context(), binary, "-commandentry", "./...")
	check.Dir = fixture
	check.Env = append(os.Environ(), "GOROOT=", "GODEBUG=toolchaintrace=1")
	output, err := check.CombinedOutput()
	status, ok := errors.AsType[*exec.ExitError](err)
	if !ok || status.ExitCode() != 3 {
		t.Fatalf("expected command diagnostics: %v\n%s", err, output)
	}

	for name, test := range cases {
		reported := strings.Contains(filepath.ToSlash(string(output)), "/cmd/"+name+"/")
		if reported != test.reject {
			t.Errorf(
				"command %s: diagnostic = %t, want %t\n%s",
				name,
				reported,
				test.reject,
				output,
			)
		}
	}

	if !strings.Contains(string(output), ":2]") {
		t.Fatalf("duplicate declarations did not receive distinct identities:\n%s", output)
	}

	if !strings.Contains(filepath.ToSlash(string(output)), "/cmd/main.go:") {
		t.Fatalf("root command implementation did not receive a diagnostic:\n%s", output)
	}

	identities := make(map[string]string)

	for line := range strings.SplitSeq(filepath.ToSlash(string(output)), "\n") {
		for _, name := range []string{"grouped", "expanded", "changed"} {
			if strings.Contains(line, "/cmd/"+name+"/") {
				_, identity, found := strings.Cut(line, "[id=")
				if found {
					identities[name] = identity
				}
			}
		}
	}

	if identities["grouped"] == "" || identities["grouped"] != identities["expanded"] ||
		identities["grouped"] == identities["changed"] {
		t.Fatalf("declaration identities do not preserve formatting-only changes: %v", identities)
	}
}
