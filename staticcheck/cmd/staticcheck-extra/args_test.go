const argumentFixture = `package sample

import "example.com/arguments/value"

type Callback func(int) int
type Alias = Callback

func sum(left, right int) int { return left + right }
func each(label string, callback func()) { callback() }
func named(callback Callback, number int) int { return callback(number) }
func alias(callback Alias) int { return callback(1) }
func imported(callback value.Callback) int { return callback(1) }
func importedAlias(callback value.Alias) int { return callback(1) }
func grouped(first, second int, callback func()) {}
func variadic(callbacks ...Callback) {}
func plain(number value.Number) int { return int(number) }

func Value() int {
	short := sum(1, 2)
	combine := sum
	nested := sum(
		combine(
			1, 2), 3)
	comment := sum(
		4, /* Preserve this comment. */ 5)
	return short + nested + comment
}


func closure() {
	each("label", func() {
		sum(1, 2)
	})
}
`

// TestArgumentLinesNativeFix checks native fixes and selected-file boundaries.
func TestArgumentLinesNativeFix(t *testing.T) {
	t.Parallel()
	binary := filepath.Join(t.TempDir(), "staticcheck-extra")
	build := exec.CommandContext(t.Context(), "go", "build", "-o", binary, ".")
	if output, err := build.CombinedOutput(); err != nil {
		t.Fatalf("build analyzer: %v\n%s", err, output)
	}

	fixture := t.TempDir()
	writeFixtureFile(t, fixture, "go.mod", "module example.com/arguments\n\ngo 1.27\n")
	writeFixtureFile(t, fixture, "calls.go", argumentFixture)
	writeFixtureFile(t, fixture, "value/value.go", `package value
type Callback func(int) int
type Alias = Callback
type Number int
`)
	sibling := "package sample\nfunc sibling(callback Callback) {}\n"
	writeFixtureFile(t, fixture, "sibling.go", sibling)
	writeFixtureFile(t, fixture, "generated.go", `// Code generated by fixture. DO NOT EDIT.
package sample
func generated(callback Callback) {}
`)
	writeFixtureFile(t, fixture, "calls_test.go", `package sample_test
import ("testing"; sample "example.com/arguments")
func TestValue(t *testing.T) { if sample.Value() != 18 { t.Fatal(sample.Value()) } }
`)
	run := func(arguments ...string) (string, error) {
		command := exec.CommandContext(t.Context(), binary, arguments...)
		command.Dir = fixture
		output, err := command.CombinedOutput()

		return string(output), err
	}
	output, err := run("-argumentlines", ".")
	var status *exec.ExitError
	if !errors.As(err, &status) || status.ExitCode() != 3 || !strings.Contains(output, "generated.go:") {
		t.Fatalf("expected argument diagnostics including generated source: %v\n%s", err, output)
	}

	selection := []string{
		"-argumentlines",
		"-argumentlines.file=" + filepath.Join(fixture, "calls.go"),
		"-argumentlines.file=" + filepath.Join(fixture, "calls_test.go"),
	}
	fix := append(append([]string{}, selection...), "-fix", ".")
	if output, err := run(fix...); err != nil {
		t.Fatalf("native fixes failed: %v\n%s", err, output)
	}

	if output, err := run(append(selection, ".")...); err != nil {
		t.Fatalf("selected files still fail: %v\n%s", err, output)
	}

	formatted, err := os.ReadFile(filepath.Join(fixture, "calls.go"))
	if err != nil {
		t.Fatal(err)
	}

	for _, expected := range []string{
		"short := sum(1, 2)", "func sum(left, right int)", "each(\"label\", func() {",
		"callback func(),\n)", "callback Callback,\n\tnumber int,\n)",
		"callback Alias,\n)", "callback value.Callback,\n)", "callback value.Alias,\n)",
		"first int,\n\tsecond int,\n", "callbacks ...Callback,\n)",
		"func plain(number value.Number)", "/* Preserve this comment. */", "\t\t\t1,\n\t\t\t2,\n",
	} {
		if !strings.Contains(string(formatted), expected) {
			t.Fatalf("native output lacks %q:\n%s", expected, formatted)
		}
	}

	unchanged, err := os.ReadFile(filepath.Join(fixture, "sibling.go"))
	if err != nil || string(unchanged) != sibling {
		t.Fatalf("unselected source changed: %v\n%s", err, unchanged)
	}

	if output, err := run(fix...); err != nil {
		t.Fatalf("repeated native fix failed: %v\n%s", err, output)
	}

	repeated, err := os.ReadFile(filepath.Join(fixture, "calls.go"))
	if err != nil || string(repeated) != string(formatted) {
		t.Fatalf("native fixes did not stabilize: %v\n%s", err, repeated)
	}

	verify := exec.CommandContext(t.Context(), "go", "test", "./...")
	verify.Dir = fixture
	if output, err := verify.CombinedOutput(); err != nil {
		t.Fatalf("formatted program changed behavior: %v\n%s", err, output)
	}
}

// TestArgumentLinesOccurrenceIDs checks correctly formatted occurrence counts.
func TestArgumentLinesOccurrenceIDs(t *testing.T) {
	t.Parallel()
	binary := filepath.Join(t.TempDir(), "staticcheck-extra")
	build := exec.CommandContext(t.Context(), "go", "build", "-o", binary, ".")
	if output, err := build.CombinedOutput(); err != nil {
		t.Fatalf("build analyzer: %v\n%s", err, output)
	}

	fixture := t.TempDir()
	writeFixtureFile(t, fixture, "go.mod", "module example.com/occurrences\n\ngo 1.27\n")
	writeFixtureFile(t, fixture, "calls.go", `package sample
func use(first, second int) {}
func init() { use(1, 2) }
func init() { use(
1, 2,
) }
func init() { use(
1, 2,
) }
`)
	check := exec.CommandContext(t.Context(), binary, "-argumentlines", ".")
	check.Dir = fixture
	output, err := check.CombinedOutput()
	var status *exec.ExitError
	if !errors.As(err, &status) || status.ExitCode() != 3 {
		t.Fatalf("expected occurrence diagnostics: %v\n%s", err, output)
	}

	identities := regexp.MustCompile(`\[id=([0-9a-f]+)-([0-9]+)\]`).FindAllStringSubmatch(string(output), -1)
	if len(identities) != 2 || identities[0][1] != identities[1][1] ||
		identities[0][2] != "2" || identities[1][2] != "3" {
		t.Fatalf("occurrences did not include the correctly formatted call:\n%s", output)
	}
}
