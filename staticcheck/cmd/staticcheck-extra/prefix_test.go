package main_test

import (
	"errors"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

// TestFilenamePrefixes checks directory recommendations for sibling files.
func TestFilenamePrefixes(t *testing.T) {
	t.Parallel()
	binary := filepath.Join(t.TempDir(), "staticcheck-extra")
	build := exec.CommandContext(t.Context(), "go", "build", "-o", binary, ".")
	if output, err := build.CombinedOutput(); err != nil {
		t.Fatalf("build analyzer: %v\n%s", err, output)
	}

	fixture := t.TempDir()
	writeFixtureFile(t, fixture, "go.mod", "module example.com/prefix\n\ngo 1.27\n")
	files := map[string]string{
		"bar_left.go": "bar", "barright.go": "bar",
		"api_alpha.go": "api", "api_archive.go": "api",
		"rpc.one.go": "rpc", "rpc.two.go": "rpc",
		"boxleft.go": "box", "boxright.go": "box",
		"log.go": "log", "log_file.go": "log",
		"net_in_linux.go": "net", "net_out_windows_amd64_test.go": "net",
		"gen_a_gen.go": "gen", "gen_b_gen.go": "gen",
		"read.go": "", "read_test.go": "", "read_darwin_arm64_test.go": "", "read_hurd.go": "",
		"éxleft.go": "", "éxright.go": "", "nested/lone.go": "", "lonecase.go": "",
	}

	for name := range files {
		writeFixtureFile(t, fixture, name, "// Code generated by fixture. DO NOT EDIT.\n//line template:1\npackage sample\n")
	}

	check := exec.CommandContext(t.Context(), binary, "-filenameprefix", "./...")
	check.Dir = fixture
	output, err := check.CombinedOutput()
	var status *exec.ExitError
	if !errors.As(err, &status) || status.ExitCode() != 3 {
		t.Fatalf("expected filename diagnostics: %v\n%s", err, output)
	}

	for name, directory := range files {
		var diagnostic string

		for line := range strings.SplitSeq(filepath.ToSlash(string(output)), "\n") {
			if strings.Contains(line, name+":") {
				diagnostic = line

				break
			}
		}

		wrongDirectory := directory != "" && !strings.Contains(diagnostic, `use directory "`+directory+`"`)
		if wrongDirectory || directory == "" && diagnostic != "" {
			t.Errorf("%s: expected directory %q, got %q", name, directory, diagnostic)
		}

		if _, err := os.Stat(filepath.Join(fixture, name)); err != nil {
			t.Errorf("source file changed location: %v", err)
		}
	}
}
