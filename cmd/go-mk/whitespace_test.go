package main_test

import (
	"path/filepath"
	"strings"
	"testing"
)

func TestWhitespaceGateChecksTestFiles(t *testing.T) {
	t.Parallel()
	consumer := newConsumerRepository(t, beforeNoticeDate)
	repository, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatal(err)
	}

	config := readConsumerFile(t, repository, "golangci.yml")
	writeConsumerFile(t, consumer, ".make/golangci.yml", config)
	writeConsumerFile(t, consumer, "notices.txt", readConsumerFile(t, repository, "notices.txt"))
	writeConsumerFile(t, consumer, appliedNoticeFile, "1\n2\n3\n4\n5\n")
	const historical = `package widget_test

import "testing"

func TestHistoricalSpacing(t *testing.T) {
	if t.Name() == "" {
		t.Fatal("empty name")
	}
	t.Log("ready")
}
`
	const original = "widget/old_test.go"
	const later = "widget/later_test.go"
	writeConsumerFile(t, consumer, original, historical)
	runConsumerGit(t, consumer, beforeNoticeDate, "add", ".")
	runConsumerGit(t, consumer, beforeNoticeDate, "commit", "--quiet", "--message", "Add historical test spacing")
	output, err := runConsumerMake(consumer, "go-mk-notice")
	if err != nil || readConsumerFile(t, consumer, appliedNoticeFile) != "1\n2\n3\n4\n5\n6\n" {
		t.Fatalf("whitespace notice failed: %v\n%s", err, output)
	}

	baseline := readConsumerFile(t, consumer, ".golangci-lint-baseline.txt")
	if !strings.Contains(baseline, original+":") || !strings.Contains(baseline, "(wsl_v5)") {
		t.Fatalf("notice omitted the historical test finding:\n%s\n%s", baseline, output)
	}

	const header = "// Code generated by fixture. DO NOT EDIT.\n"
	writeConsumerFile(t, consumer, later, header+strings.Replace(historical, "TestHistoricalSpacing", "TestLaterSpacing", 1))
	scoped := []string{"lint-files", "LINT_FILES=" + later, "STATICCHECK_EXTRA_FLAGS=-argumentlines", "STATICCHECK_EXTRA_TEST_FLAGS="}

	for _, args := range [][]string{{"lint-golangci"}, scoped} {
		output, err := runConsumerMake(consumer, args...)
		if err == nil || !strings.Contains(output, later+":") || !strings.Contains(output, "(wsl_v5)") || strings.Contains(output, original+":") {
			t.Fatalf("%s did not report only the later test spacing: %v\n%s", args[0], err, output)
		}
	}

	for _, override := range []string{
		"GOLANGCI_LINT_EXCLUDE_PATHS=_test\\.go:",
		"GOLANGCI_LINT_RUN_FLAGS=-c .make/golangci.yml --enable-only=revive",
	} {
		output, err := runConsumerMake(consumer, append(scoped, override)...)
		if err != nil {
			t.Fatalf("explicit lint selection %q failed: %v\n%s", override, err, output)
		}
	}

	writeConsumerFile(t, consumer, ".make/golangci.yml", strings.Replace(config, "&go_makefile_test_files ", "", 1))
	if output, err := runConsumerMake(consumer, scoped...); err != nil {
		t.Fatalf("explicit test path exclusion failed: %v\n%s", err, output)
	}
}
